#!/usr/bin/env bash
# Baseline schema for the tables created in the Supabase dashboard (test report D8, 4 Nov 2026).
# orders, profiles and documents exist in production but no migration creates them, so staging
# cannot be rebuilt from the repo. Run this ONCE from a machine logged in to the Supabase CLI:
#
#   supabase login
#   supabase link --project-ref <production project ref>
#   bash supabase/scripts/dump-baseline.sh
#
# It writes the schema only (no customer data) to a migration dated before every other migration,
# then marks it as already applied in production, so it never runs there.
set -euo pipefail
OUT="supabase/migrations/20261001000000_baseline_schema.sql"
supabase db dump --linked --schema public -f "$OUT"
{ echo "-- Baseline: schema of public.* as it stood in production on $(date -u +%F)."; echo "-- Schema only, no data. Generated by supabase/scripts/dump-baseline.sh (test report D8)."; cat "$OUT"; } > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"
supabase migration repair --status applied 20261001000000
echo "Wrote $OUT. Review it, check no secrets or data are in it, then commit it."
